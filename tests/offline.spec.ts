import { expect, test } from '@playwright/test'

test('la copia local abre sin red y conserva el plan, el kit y los contactos al reconectar', async ({ context, page, request }) => {
  const manifestResponse = await request.get('/manifest.webmanifest')
  expect(manifestResponse.ok()).toBe(true)
  const manifest = await manifestResponse.json()
  expect(manifest.display).toBe('standalone')
  for (const icon of manifest.icons) {
    const response = await request.get('/' + icon.src)
    expect(response.ok()).toBe(true)
    expect(response.headers()['content-type']).toContain('image/png')
  }

  await page.goto('/')
  await expect(page.getByText('Lista para usar sin conexión', { exact: true })).toBeVisible()
  await page.getByText('Lista para usar sin conexión', { exact: true }).click()
  await expect(page.locator('time')).toHaveAttribute('datetime', /^\d{4}-\d{2}-\d{2}T/)
  await page.close()

  await context.setOffline(true)
  const offline = await context.newPage()
  const navigationResponse = await offline.goto('/#preparacion')
  expect(navigationResponse?.fromServiceWorker()).toBe(true)
  await expect(offline.getByRole('heading', { name: 'Mi kit de 72 horas' })).toBeVisible()
  await expect(offline.getByText('Sin conexión', { exact: true })).toBeVisible()
  await offline.getByText('Plan familiar y contactos', { exact: true }).click()
  await offline.getByRole('textbox', { name: 'Plan familiar', exact: true }).fill('Reunión de prueba')
  await offline.getByRole('button', { name: 'Guardar plan' }).click()
  await offline.getByLabel('Nombre del contacto').fill('Contacto de prueba')
  await offline.getByLabel('Teléfono', { exact: true }).fill('+34 600 000 000')
  await offline.getByRole('button', { name: 'Añadir contacto' }).click()
  await expect(offline.getByRole('link', { name: '+34 600 000 000' })).toHaveAttribute('href', 'tel:+34600000000')
  await offline.getByLabel('Estado de Agua potable').selectOption('disponible')
  await expect(offline.getByText('Datos guardados en este dispositivo', { exact: true })).toBeVisible()

  const nav = offline.getByRole('navigation', { name: 'Navegación principal' })
  await nav.getByRole('link', { name: 'Guías' }).click()
  await offline.getByText('Inundaciones', { exact: true }).click()
  await expect(offline.getByRole('link', { name: 'Protección Civil y Emergencias' })).toBeVisible()
  await nav.getByRole('link', { name: 'Energía' }).click()
  await expect(offline.getByText('8.0 horas', { exact: true })).toBeVisible()
  await nav.getByRole('link', { name: 'Avisos' }).click()
  await expect(offline.getByText('Sin datos de alertas guardados.')).toBeVisible()
  await expect(offline.getByText('Sin conexión. El estado actual de los avisos no se puede comprobar.')).toBeVisible()

  await context.setOffline(false)
  await expect(offline.getByText('Con conexión', { exact: true })).toBeVisible()
  await nav.getByRole('link', { name: 'Inicio' }).click()
  await expect(offline.getByText('Lista para usar sin conexión', { exact: true })).toBeVisible()
  await offline.reload()
  await expect(offline.getByRole('region', { name: 'Tu kit de emergencia' })).toContainText('1 de 8 elementos disponibles')
  await nav.getByRole('link', { name: 'Mi kit' }).click()
  await offline.getByText('Plan familiar y contactos', { exact: true }).click()
  await expect(offline.getByRole('textbox', { name: 'Plan familiar', exact: true })).toHaveValue('Reunión de prueba')
  await expect(offline.getByRole('link', { name: '+34 600 000 000' })).toBeVisible()
})
